/// Deepest nesting of objects in a contract, the root object included (ADR 0009 C4).
pub const MAX_OBJECT_LEVELS: usize = 4;

crate::closed_enum! {
    /// Whether a schema describes what the engine reads or what it writes.
    pub enum Direction {
        /// What a client sends: every object is closed, an unknown member is refused.
        Input = "input",
        /// What the engine writes: objects are open, clients accept members they do not know.
        Output = "output",
    }
}

/// Why a generated schema leaves the rules of the contracts.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Problem {
    /// The root, a definition or a member has no description.
    MissingDescription,
    /// An enum value whose meaning the description does not give.
    UndocumentedValue(String),
    /// A text enum value that is not `snake_case` (ADR 0009 C4).
    NotSnakeCase(String),
    /// A value named by a condition that the declared schema of the member it tests does not
    /// accept, such as a misspelt status: the condition would never hold.
    UnacceptedValue(String),
    /// `additionalProperties` in an output, written by the derive (for example
    /// `deny_unknown_fields`, or a map flattened beside declared members): an output is open
    /// (ADR 0009 C5). A pure map, which declares no member, keeps the schema of its values.
    ClosedOutput,
    /// Objects nested deeper than [`MAX_OBJECT_LEVELS`].
    TooDeep,
    /// An object of an input with neither `additionalProperties: false` nor a schema of its
    /// members that is not a free object of the input: an input is closed (ADR 0009 C5, ADR
    /// 0030 G2).
    OpenInput,
}

/// A generated schema that leaves the rules of the contracts, and where.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ContractError {
    /// Pointer into the generated schema.
    pub pointer: Pointer,
    /// What is wrong.
    pub problem: Problem,
}

impl fmt::Display for ContractError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let place = if self.pointer.as_str().is_empty() {
            "the root of the schema"
        } else {
            self.pointer.as_str()
        };
        match &self.problem {
            Problem::MissingDescription => write!(f, "at {place}: no description"),
            Problem::UndocumentedValue(value) => write!(
                f,
                "at {place}: the description gives no meaning for the value {value}"
            ),
            Problem::NotSnakeCase(value) => {
                write!(f, "at {place}: the enum value {value} is not snake_case")
            }
            Problem::UnacceptedValue(value) => write!(
                f,
                "at {place}: the condition names the value {value}, which its member does not \
                 accept"
            ),
            Problem::ClosedOutput => write!(
                f,
                "at {place}: `additionalProperties` that closes an output, which is open"
            ),
            Problem::OpenInput => write!(
                f,
                "at {place}: an object of an input that is open and not a declared free object"
            ),
            Problem::TooDeep => write!(
                f,
                "at {place}: objects nested deeper than {MAX_OBJECT_LEVELS} levels"
            ),
        }
    }
}

impl std::error::Error for ContractError {}

/// The schema of `T` for `direction`, inside the rules of the contracts.
///
/// The schema describes the serialised form of `T` for an output and the form it reads for an
/// input. Members are in the byte order of their keys; `required` keeps the order of
/// declaration.
///
/// # Errors
///
/// A [`ContractError`] naming the first place found where the schema leaves the rules of this
/// module.
pub fn schema_for<T: JsonSchema>(direction: Direction) -> Result<Value, ContractError> {
    let settings = SchemaSettings::draft2020_12();
    let settings = match direction {
        Direction::Input => settings.for_deserialize(),
        Direction::Output => settings.for_serialize(),
    };
    let schema = settings
        .with_transform(transform::Subset { direction })
        .into_generator()
        .into_root_schema_for::<T>()
        .to_value();
    check::check(&schema, direction)?;
    Ok(schema)
}

/// Where the snapshots under `schemas/` are published: the documentation site, the `homepage`
/// of the workspace manifest, then `schemas/`. The `$id` of a snapshot is this URL followed by
/// its path under `schemas/` (ADR 0030 G5), written only by [`snapshot`].
pub const PUBLISHED_AT: &str = concat!(env!("CARGO_PKG_HOMEPAGE"), "schemas/");

/// The text of the snapshot of `schema` at `path` under `schemas/`, for example
/// `envelope/result/v1.json`: the schema with its `$id`, keys in byte order, two-space
/// indentation, UTF-8 without escapes and a final newline (ADR 0030 G6). The same schema and
/// path always give the same bytes. A schema that is not an object gets no `$id`; the loader of
/// the core refuses it. This function is the only source of the snapshot text, written
/// unchanged by `just generate` (`scripts/schema_snapshots.py`).
///
/// # Errors
///
/// The error of `serde_json` when the schema cannot be written, which a JSON value never gives.
pub fn snapshot(mut schema: Value, path: &str) -> Result<String, serde_json::Error> {
    if let Some(object) = schema.as_object_mut() {
        object.insert("$id".to_owned(), format!("{PUBLISHED_AT}{path}").into());
    }
    let mut text = serde_json::to_string_pretty(&schema)?;
    text.push('\n');
    Ok(text)
}

/// A contract type, the function that generates its schema, and the one that reads a document
/// into the type and writes it again (the round trip of ADR 0030 G1).
#[derive(Debug, Clone, Copy)]
pub struct Registered {
    /// Name of the type, which is also the `title` of its schema.
    pub name: &'static str,
    /// [`schema_for`] the type.
    pub schema: fn(Direction) -> Result<Value, ContractError>,
    /// [`reread`] into the type.
    pub reread: Reread,
}

/// A document read into a contract type and written again, as [`reread`] does (ADR 0030 G1).
pub type Reread = fn(&Value) -> Result<Value, serde_json::Error>;

/// `document` read into `T` and written again: a document the schema of `T` accepts must give
/// itself back, members set to null and members `T` does not know left out.
///
/// # Errors
///
/// The error of `serde_json` when `document` is not a value of `T`.
pub fn reread<T: Serialize + DeserializeOwned>(
    document: &Value,
) -> Result<Value, serde_json::Error> {
    serde_json::to_value(T::deserialize(document)?)
}

/// The registration of a contract type, named as written, or by the name of its schema for a
/// generic type with its parameters given.
macro_rules! registered {
    ($t:ty) => {
        registered!($t as stringify!($t))
    };
    ($t:ty as $name:expr) => {
        Registered {
            name: $name,
            schema: schema_for::<$t>,
            reread: reread::<$t>,
        }
    };
}

/// The envelope of any data. The envelope is generic over the data of a command (ADR 0030 G1);
/// a generic type has no schema until its parameter is given, so it is registered as
/// `Envelope<Value>` under the name of its schema, `Envelope`. The output schema of a command
/// is the envelope with the data type of that command.
const ENVELOPE: Registered = registered!(Envelope<Value> as "Envelope");

/// The output of the command `validate`: the envelope with its data, the file
/// `v<N>.output.json` of the contract `commands/validate`.
const VALIDATE_OUTPUT: Registered = registered!(Envelope<ValidateData> as "Envelope<ValidateData>");

